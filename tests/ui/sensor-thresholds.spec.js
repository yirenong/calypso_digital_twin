import { test, expect } from '@playwright/test'
test('individual sensor rules persist, notify on crossings, rearm, and remain scoped', async ({page}) => {
  await page.clock.install()
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/water-management/thresholds')
  await page.getByRole('tab',{name:'Sensor thresholds'}).click()
  await page.getByRole('button',{name:'Add sensor rule'}).click()
  let row=page.locator('.sensor-row.threshold-setting-row').first()
  await row.getByLabel('Sensor target',{exact:true}).selectOption('water-c-03')
  await row.getByLabel('Sensor limit',{exact:true}).fill('6')
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await expect(page.locator('.threshold-active li')).toContainText('water-c-03')
  await expect(page.locator('.notification-toast')).toContainText('water-c-03')
  await page.getByRole('button',{name:'Dismiss notification'}).click()
  await page.evaluate(async()=>{const api=await import('/calypso-data.js');api.updateSensor('water-c-03',{rate:9})})
  await page.getByRole('button',{name:'Notifications',exact:true}).click()
  await expect(page.locator('.notification-panel li')).toHaveCount(1)
  await page.getByRole('button',{name:'Close notifications'}).click()
  await page.evaluate(async()=>{const api=await import('/calypso-data.js');api.updateSensor('water-c-03',{rate:5});api.updateSensor('water-c-03',{rate:7})})
  await page.clock.fastForward(180000)
  await expect(page.locator('.notification-toast')).toContainText('water-c-03')
  await page.getByRole('button',{name:'Dismiss notification'}).click()
  await page.getByRole('button',{name:'Add sensor rule'}).click()
  row=page.locator('.sensor-row.threshold-setting-row').last()
  await row.getByLabel('Sensor target',{exact:true}).selectOption('water-b-04')
  await row.getByLabel('Sensor metric',{exact:true}).selectOption('offline')
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await expect(page.locator('.threshold-active li')).toHaveCount(2)
  await page.reload()
  await page.getByRole('tab',{name:'Sensor thresholds'}).click()
  await expect(page.locator('.sensor-row.threshold-setting-row')).toHaveCount(2)
  await expect(page.getByLabel('Sensor limit',{exact:true}).first()).toHaveValue('6')
  await page.goto('/energy-management/thresholds')
  await page.getByRole('tab',{name:'Sensor thresholds'}).click()
  await expect(page.getByText('No sensor rules yet')).toBeVisible()
  await page.getByRole('button',{name:'Add sensor rule'}).click()
  await page.getByLabel('Sensor target',{exact:true}).selectOption('energy-b-02')
  await page.getByLabel('Sensor metric',{exact:true}).selectOption('fault')
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await expect(page.locator('.threshold-active li')).toContainText('energy-b-02')
  await page.goto('/water-management/thresholds')
  await page.getByRole('tab',{name:'Sensor thresholds'}).click()
  await expect(page.locator('.sensor-row.threshold-setting-row')).toHaveCount(2)
  await page.locator('.sensor-row.threshold-setting-row').last().getByRole('button',{name:'Remove sensor rule'}).click()
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await expect(page.locator('.threshold-active li')).toHaveCount(1)
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
