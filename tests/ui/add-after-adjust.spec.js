import { test, expect } from '@playwright/test'
const readLayout = page => page.locator('.dashboard-grid').evaluate(el => el.gridstack.engine.nodes.map(({id,x,y,w,h}) => ({id,x,y,w,h})).sort((a,b) => a.id.localeCompare(b.id)))
for (const width of [1440, 1100, 390]) {
  test(`adding cards keeps in-progress positions and sizes at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1200 })
    await page.goto('/dashboard')
    await page.getByRole('button', { name: 'Customize dashboard' }).click()
    const grip = await page.getByRole('button', { name: 'Move Energy consumption', exact: true }).boundingBox()
    await page.mouse.move(grip.x + 15, grip.y + 12); await page.mouse.down()
    await page.mouse.move(grip.x + 15 + (width > 700 ? 280 : 0), grip.y + 12 + 128, { steps: 20 }); await page.mouse.up()
    await expect(page.locator('.dashboard-grid')).not.toHaveClass(/is-adjusting/)
    const energy = page.locator('[data-widget-id="energy"]')
    await energy.scrollIntoViewIfNeeded()
    const corner = await energy.locator('.ui-resizable-se').boundingBox()
    await page.mouse.move(corner.x + 12, corner.y + 12); await page.mouse.down()
    await page.mouse.move(corner.x + 12, corner.y + 12 + 64, { steps: 15 }); await page.mouse.up()
    await expect(page.locator('.dashboard-grid')).not.toHaveClass(/is-adjusting/)
    const before = await readLayout(page)
    await page.getByRole('button', { name: 'Find widgets', exact: true }).click()
    for (const title of ['Peak demand', 'Building occupancy']) {
      await page.getByRole('button', { name: `Add ${title}`, exact: true }).click()
      const current = await readLayout(page)
      expect(current.filter(item => before.some(old => old.id === item.id))).toEqual(before)
    }
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(page.locator('[data-widget-id="occupancy"]')).toHaveCount(0)
    expect((await readLayout(page)).filter(item => before.some(old => old.id === item.id))).toEqual(before)
    await page.getByRole('button', { name: 'Save dashboard' }).click()
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('calypso.dashboard.v1')))
    await page.reload()
    await page.getByRole('button', { name: 'Customize dashboard' }).click()
    await page.getByRole('button', { name: 'Find widgets', exact: true }).click()
    await page.getByRole('button', { name: 'Add Building occupancy', exact: true }).click()
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Save dashboard' }).click()
    const savedAfter = await page.evaluate(() => JSON.parse(localStorage.getItem('calypso.dashboard.v1')))
    expect(savedAfter.filter(item => saved.some(old => old.id === item.id))).toEqual(saved)
  })
}
