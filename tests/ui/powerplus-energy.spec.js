import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('PowerPlus dashboard metrics, AC simulation controls and tenant analytics', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'PowerPlus-Admin'))
  await page.route('**/visualiser/**', route => route.fulfill({ body: 'Twin preview' }))
  await page.goto('/dashboard')
  for (const id of ['tse', 'energy', 'water', 'waste', 'renewable', 'acmv-energy', 'lighting-energy', 'lifts-energy']) await expect(page.locator(`[data-widget-id="${id}"]`)).toBeVisible()
  await expect(page.locator('[data-widget-id="tse"]')).toContainText('0.72')
  await expect(page.locator('[data-widget-id="waste"]')).toContainText('185')
  await expect(page.locator('[data-widget-id="renewable"]')).toContainText('420')
  await page.getByRole('link', { name: 'Energy Management', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Adaptive AC Control System', exact: true })).toBeVisible()
  mkdirSync('tmp/pdfs', { recursive: true })
  await page.locator('.ac-control-panel').screenshot({ path: 'tmp/pdfs/ac-controls-desktop.png' })
  await page.getByLabel('Control mode', { exact: true }).selectOption('Manual')
  await page.getByLabel('Manual fan speed (%)', { exact: true }).fill('90')
  await page.getByRole('button', { name: 'Apply AC controls', exact: true }).click()
  await expect(page.locator('.ac-state')).toHaveText('Manual operation')
  await expect.poll(async () => Number((await page.getByTestId('ac-power').textContent()).replace(/[^0-9.]/g, ''))).toBeGreaterThan(180)
  await page.reload()
  await expect(page.getByLabel('Control mode', { exact: true })).toHaveValue('Manual')
  await expect(page.getByLabel('Manual fan speed (%)', { exact: true })).toHaveValue('90')
  await page.getByLabel('AC system enabled', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Apply AC controls', exact: true }).click()
  await expect(page.getByTestId('ac-power')).toHaveText('0 kW')
  await page.getByRole('button', { name: 'Reset controls', exact: true }).click()
  await page.getByRole('link', { name: 'Tenant energy', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Add participating tenant', exact: true })).toHaveCount(0)
  for (const name of ['Tenant continuous demand monitoring', 'Tenant energy consumption history', 'Tenant daily energy performance comparison']) await expect(page.getByRole('img', { name, exact: true })).toBeVisible()
  await expect(page.locator('.tenant-kpis')).toContainText('Current demand')
  await page.getByLabel('Tenant', { exact: true }).selectOption('demo-tenant-2')
  await expect(page.locator('.tenant-analytics')).toBeVisible()
  await page.locator('.tenant-analytics').screenshot({ path: 'tmp/pdfs/tenant-analytics-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/energy-management')
  await expect(page.locator('.ac-control-panel')).toBeVisible()
  await page.locator('.ac-control-panel').screenshot({ path: 'tmp/pdfs/ac-controls-mobile.png' })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
