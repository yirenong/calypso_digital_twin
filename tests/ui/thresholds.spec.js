import { test, expect } from '@playwright/test'
test('system threshold pages save, alert once per crossing, and retain local history', async ({ page }) => {
  await page.clock.install()
  const errors=[]; page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/water-management')
  await page.getByRole('link',{name:'Thresholds & alerts'}).click()
  await expect(page.getByRole('heading',{name:'Water Management thresholds'})).toBeVisible()
  await page.getByLabel('Enable Supply pressure threshold').check()
  await page.getByLabel('Supply pressure block').selectOption('block-b')
  await page.getByLabel('Supply pressure limit').fill('3')
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await expect(page.getByRole('status').filter({hasText:'Threshold alert'})).toContainText('Level 2')
  await expect(page.locator('.threshold-active li')).toHaveCount(1)
  await page.getByRole('button',{name:'Dismiss notification'}).click()
  await page.getByRole('button',{name:'Notifications',exact:true}).click()
  await expect(page.locator('.notification-panel li')).toHaveCount(1)
  await page.getByRole('button',{name:'Close notifications'}).click()
  await page.evaluate(async()=>{ const api=await import('/calypso-data.js'); api.updateBlock('block-b',{waterPressureBar:2.7}) })
  await page.getByRole('button',{name:'Notifications',exact:true}).click()
  await expect(page.locator('.notification-panel li')).toHaveCount(1)
  await page.getByRole('button',{name:'Close notifications'}).click()
  await page.evaluate(async()=>{ const api=await import('/calypso-data.js'); api.updateBlock('block-b',{waterPressureBar:3.2}); api.updateBlock('block-b',{waterPressureBar:2.6}) })
  await page.clock.fastForward(180000)
  await page.getByRole('button',{name:'Dismiss notification'}).click()
  await page.getByRole('button',{name:'Notifications',exact:true}).click()
  await expect(page.locator('.notification-panel li')).toHaveCount(2)
  await page.getByRole('button',{name:'Mark all read'}).click()
  await expect(page.locator('.notification-count')).toHaveCount(0)
  await page.getByRole('button',{name:'Close notifications'}).click()
  await page.getByRole('checkbox',{name:'Play notification sound (all systems)'}).check()
  await page.getByRole('button',{name:'Test notification',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Test notification'})).toBeVisible()
  await expect(page.getByText('Sound activated for this session.',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'Dismiss notification'}).click()
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await page.reload()
  await expect(page.getByLabel('Supply pressure limit')).toHaveValue('3')
  await expect(page.getByLabel('Enable Supply pressure threshold')).toBeChecked()
  for(const [path,title] of [['/building-management/thresholds','BMS'],['/energy-management/thresholds','Energy Management'],['/security-cctv/thresholds','Security and CCTV'],['/dashboard/thresholds','Dashboard']]) {
    await page.goto(path); await expect(page.getByRole('heading',{name:title+' thresholds'})).toBeVisible()
  }
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('button',{name:'Save thresholds'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
