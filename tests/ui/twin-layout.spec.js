test('resizing a bottom-right card and changing group sizes keeps top-left fixed',async({page})=>{
 await setup(page)
 await page.getByRole('tab',{name:'Water',exact:true}).click()
 await page.getByRole('button',{name:'Customize twin dashboard'}).click()
 const card=page.locator('[data-panel="water"]'),handle=page.getByRole('button',{name:'Resize Water consumption panel',exact:true})
 const geometry=locator=>locator.evaluate(el=>{const area=el.parentElement,bounds=area.getBoundingClientRect(),r=el.getBoundingClientRect();return{left:r.left-bounds.left+area.scrollLeft,top:r.top-bounds.top+area.scrollTop,width:r.width,height:r.height}})
 await handle.scrollIntoViewIfNeeded();const before=await geometry(card),grip=await handle.boundingBox()
 await page.mouse.move(grip.x+14,grip.y+14);await page.mouse.down();await page.mouse.move(grip.x-26,grip.y-26,{steps:8});await page.mouse.up()
 const after=await geometry(card)
 expect(after.left).toBeCloseTo(before.left,0);expect(after.top).toBeCloseTo(before.top,0)
 expect(after.width).toBeCloseTo(before.width-40,0);expect(after.height).toBeCloseTo(before.height-40,0)
 const right=page.locator('[data-panel="systems"]'),oldRight=await geometry(right)
 await page.getByRole('button',{name:'Dock sizes',exact:true}).click()
 await page.getByRole('slider',{name:'Side panel width'}).fill('400')
 await page.getByRole('spinbutton',{name:'Side panel height',exact:true}).fill('700')
 await page.getByRole('button',{name:'Close dock sizes'}).click()
 const newRight=await geometry(right)
 expect(newRight.left).toBeCloseTo(oldRight.left,0);expect(newRight.top).toBeCloseTo(oldRight.top,0)
})
