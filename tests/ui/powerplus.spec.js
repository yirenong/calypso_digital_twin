test('PowerPlus uses existing system pages and removes disclosure', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'PowerPlus-Admin'))
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Work orders', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Building operations', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Building operations', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Work orders', exact: true })).toBeVisible()
  await expect(page.getByTestId('tse-value')).toContainText('0.72')
  await expect(page.locator('.acmv-efficiency')).toContainText('180')
  await expect(page.locator('.acmv-efficiency')).toContainText('250')
  for (const name of ['Operational dashboard', 'Adaptive AC', 'Open BMS & assets', 'Data disclosure', 'Feedback & service', 'Community']) await expect(page.getByRole('navigation').getByRole('link', { name, exact: true })).toHaveCount(0)
  await page.goto('/powerplus/adaptive-ac')
  await expect(page).toHaveURL(/\/energy-management$/)
  await expect(page.getByRole('heading', { name: 'Adaptive AC performance plan', exact: true })).toBeVisible()
  await page.goto('/powerplus/open-bms')
  await expect(page).toHaveURL(/\/building-management$/)
  await expect(page.getByRole('heading', { name: 'Point list and naming convention', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Green Mark certification', exact: true })).toBeVisible()
  await expect(page.locator('.green-mark-badge')).not.toHaveAttribute('href')
  await expect(page.locator('.green-mark-badge img')).toBeVisible()
  for (const path of ['/powerplus/disclosure', '/powerplus/feedback', '/powerplus/community']) {
    await page.goto(path)
    await expect(page.getByRole('heading', { name: /Page not found/i })).toBeVisible()
  }
})

test('PowerPlus opens the customizable Dashboard with exactly two retained tabs', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'PowerPlus-Admin'))
  await page.route('**/visualiser/**', route => route.fulfill({ body: 'Twin preview' }))
  await page.goto('/dashboard')
  await expect(page.getByRole('tab')).toHaveCount(2)
  await expect(page.getByRole('tab', { name: 'Dashboard', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  await page.getByRole('button', { name: 'Remove Indoor temperature' }).click()
  await page.getByRole('button', { name: 'Save dashboard' }).click()
  await page.getByRole('tab', { name: 'Digital Twin', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard\/digital-twin$/)
  await page.getByRole('tab', { name: 'Dashboard', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await expect(page.locator('.widget-grid')).not.toContainText('Indoor temperature')
  await page.reload()
  await expect(page.locator('.widget-grid')).not.toContainText('Indoor temperature')
  await expect(page.getByRole('button', { name: 'Customize dashboard' })).toBeVisible()
  await page.goto('/dashboard/widgets')
  await expect(page).toHaveURL(/\/dashboard$/)
})
