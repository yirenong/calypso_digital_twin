import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('PowerPlus requirements pages save workflows and restore them across reload', async ({ page }) => {
  test.setTimeout(60000)
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'PowerPlus-Admin'))
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/powerplus/managerial')
  await page.getByLabel('Gross floor area (m²)', { exact: true }).fill('10000')
  await page.getByLabel('Total net lettable area (m²)', { exact: true }).fill('8000')
  await page.getByRole('button', { name: 'Save building profile' }).click()
  await expect(page.locator('.pp-metrics:visible').first()).not.toContainText('Configure gross floor area')
  await page.getByRole('link', { name: 'Building operations', exact: true }).click()
  await page.getByLabel('Task', { exact: true }).fill('Inspect AHU')
  await page.getByLabel('Equipment', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Assigned to', { exact: true }).fill('Facilities team')
  await page.getByRole('button', { name: 'Create work order' }).click()
  await page.getByLabel('Status for Inspect AHU', { exact: true }).selectOption('In progress')
  await page.reload()
  await expect(page.getByLabel('Status for Inspect AHU', { exact: true })).toHaveValue('In progress')
  await page.getByRole('link', { name: 'Tenant energy', exact: true }).click()
  await expect(page.locator('.pp-metrics:visible')).toContainText('3')
  await expect(page.locator('.pp-page:visible')).toContainText('Tenant A')
  await expect(page.getByRole('heading', { name: 'Continuous demand monitoring', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Add participating tenant', exact: true })).toHaveCount(0)
  await expect(page.getByRole('img', { name: 'Tenant daily energy performance comparison', exact: true })).toBeVisible()
  mkdirSync('tmp/pdfs', { recursive: true })
  for (const path of ['/dashboard', '/building-operations', '/powerplus/managerial', '/energy-management', '/powerplus/tenant-energy', '/building-management']) {
    await page.goto(path)
    await expect(page.locator('main:visible h1').first()).toBeVisible()
    await page.screenshot({ path: `tmp/pdfs/powerplus-ui-${path.replaceAll('/', '-')}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/powerplus/tenant-energy')
  await expect(page.locator('.pp-page h1')).toBeVisible()
  await page.screenshot({ path: 'tmp/pdfs/powerplus-ui-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

