import { test, expect } from '@playwright/test'
const tile = (page, id) => page.locator(`.grid-stack-item[data-widget-id="${id}"]`)
test('adjustments keep one grid instance and defer chart resizing and history updates until release', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1200 })
  await page.goto('/dashboard')
  await expect(page.locator('.dashboard-grid')).toBeVisible()
  await page.evaluate(() => { window.testGrid = document.querySelector('.dashboard-grid').gridstack })
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  expect(await page.evaluate(() => document.querySelector('.dashboard-grid').gridstack === window.testGrid)).toBe(true)
  const chart = tile(page, 'energy-trend')
  await chart.getByRole('button', { name: 'Daily', exact: true }).click()
  await chart.scrollIntoViewIfNeeded()
  await chart.locator('canvas').evaluate(canvas => {
    window.canvasResizes = 0
    window.canvasObserver = new MutationObserver(records => { window.canvasResizes += records.filter(r => ['width', 'height'].includes(r.attributeName)).length })
    window.canvasObserver.observe(canvas, { attributes: true })
  })
  const grip = await chart.locator('.ui-resizable-se').boundingBox()
  await page.mouse.move(grip.x + 12, grip.y + 12); await page.mouse.down()
  await page.mouse.move(grip.x + 12 - 60, grip.y + 12 + 80, { steps: 20 })
  await expect(page.locator('.dashboard-grid')).toHaveClass(/is-adjusting/)
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  expect(await page.evaluate(() => window.canvasResizes)).toBeLessThan(6)
  expect(await chart.evaluate(el => getComputedStyle(el).transitionDuration)).toBe('0s')
  await page.mouse.up()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeEnabled()
  await expect(page.locator('.dashboard-grid')).not.toHaveClass(/is-adjusting/)
  await expect.poll(() => chart.locator('canvas').evaluate(canvas => Math.abs(canvas.width - canvas.parentElement.clientWidth * window.devicePixelRatio))).toBeLessThan(2)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(chart).toHaveAttribute('gs-h', '21')
  await page.getByRole('button', { name: 'Find widgets', exact: true }).click()
  await page.getByRole('button', { name: 'Add Peak demand', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(tile(page, 'energy-peak')).toBeVisible()
  await page.getByRole('button', { name: 'Remove Peak demand', exact: true }).click()
  await expect(tile(page, 'energy-peak')).toHaveCount(0)
  expect(await page.evaluate(() => document.querySelector('.dashboard-grid').gridstack === window.testGrid)).toBe(true)
  await expect(chart.locator('.chart-component')).toHaveAttribute('data-period', 'daily')
  await page.evaluate(() => window.canvasObserver.disconnect())
})
test('drag, corner resize, undo/redo and save preserve a free dashboard layout', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1200 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  const energy = tile(page, 'energy')
  const start = await page.getByRole('button', { name: 'Move Energy consumption', exact: true }).boundingBox()
  await page.mouse.move(start.x + 20, start.y + 12)
  await page.mouse.down()
  await page.mouse.move(start.x + 20 + 280, start.y + 12 + 128, { steps: 20 })
  await page.mouse.up()
  await expect(energy).not.toHaveAttribute('gs-y', '0')
  const moved = await energy.getAttribute('gs-y')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(energy).toHaveAttribute('gs-y', '0')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(energy).toHaveAttribute('gs-y', moved)
  const handle = await energy.locator('.ui-resizable-se').boundingBox()
  await page.mouse.move(handle.x + 12, handle.y + 12)
  await page.mouse.down()
  await page.mouse.move(handle.x + 12 + 100, handle.y + 12 + 64, { steps: 15 })
  await page.mouse.up()
  await expect(energy).not.toHaveAttribute('gs-h', '7')
  const size = { x: await energy.getAttribute('gs-x'), y: await energy.getAttribute('gs-y'), w: await energy.getAttribute('gs-w'), h: await energy.getAttribute('gs-h') }
  await page.getByRole('button', { name: 'Save dashboard' }).click()
  await page.reload()
  for (const [field, value] of Object.entries(size)) await expect(energy).toHaveAttribute(`gs-${field}`, value)
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  const again = await page.getByRole('button', { name: 'Move Energy consumption', exact: true }).boundingBox()
  await page.mouse.move(again.x + 20, again.y + 12); await page.mouse.down()
  await page.mouse.move(again.x + 20 - 190, again.y + 12 - 64, { steps: 20 }); await page.mouse.up()
  await expect(energy).not.toHaveAttribute('gs-y', size.y)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  for (const [field, value] of Object.entries(size)) await expect(energy).toHaveAttribute(`gs-${field}`, value)
  expect(errors).toEqual([])
})
test('precise size settings, keyboard movement, mobile saving and Find widgets remain usable', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Find widgets', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search widgets' }).fill('peak')
  await page.getByRole('button', { name: 'Add Peak demand', exact: true }).click()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: 'Resize Peak demand', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Widget column' }).fill('7')
  await page.getByRole('spinbutton', { name: 'Widget row' }).fill('40')
  await page.getByRole('spinbutton', { name: 'Widget width' }).fill('6')
  await page.getByRole('spinbutton', { name: 'Widget height' }).fill('8')
  await page.getByRole('button', { name: 'Apply size & position' }).click()
  await expect(tile(page, 'energy-peak')).toHaveAttribute('gs-x', '6')
  await expect(tile(page, 'energy-peak')).toHaveAttribute('gs-y', '39')
  await page.getByRole('button', { name: 'Move Peak demand', exact: true }).press('ArrowUp')
  await expect(tile(page, 'energy-peak')).toHaveAttribute('gs-y', '38')
  await page.getByRole('button', { name: 'Save dashboard' }).click()
  const desktop = await page.evaluate(() => JSON.parse(localStorage.getItem('calypso.dashboard.v1')))
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.locator('.dashboard-grid').evaluate(el => el.gridstack.getColumn())).toBe(1)
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  await page.getByRole('button', { name: 'Save dashboard' }).click()
  const mobileSaved = await page.evaluate(() => JSON.parse(localStorage.getItem('calypso.dashboard.v1')))
  expect(mobileSaved).toEqual(desktop)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  await page.getByRole('button', { name: 'Resize Peak demand', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Widget height' }).fill('9')
  await page.getByRole('button', { name: 'Apply size & position' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await tile(page, 'energy-peak').evaluate(el => el.gridstackNode.w)).toBe(1)
  await page.getByRole('button', { name: 'Save dashboard' }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.reload()
  await expect(tile(page, 'energy-peak')).toHaveAttribute('gs-x', '6')
  await expect(tile(page, 'energy-peak')).toHaveAttribute('gs-y', '38')
  await expect(tile(page, 'energy-peak')).toHaveAttribute('gs-h', '9')
  await page.getByRole('button', { name: 'Customize dashboard' }).click()
  await page.getByRole('button', { name: 'Tidy layout', exact: true }).click()
  await expect(tile(page, 'energy-peak')).not.toHaveAttribute('gs-y', '38')
  await page.screenshot({ path: 'test-results/flexible-layout-final.png', fullPage: true, animations: 'disabled' })
})
