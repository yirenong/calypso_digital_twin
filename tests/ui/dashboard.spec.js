test('all chart intervals change histories independently and block totals follow the filter', async ({ page }) => {
  await page.goto('/')
  const energy = page.locator('.card').filter({ has: page.getByRole('heading', { name: 'Energy consumption trend', exact: true }) })
  const water = page.locator('.card').filter({ has: page.getByRole('heading', { name: 'Water consumption trend', exact: true }) })
  await expect(energy.locator('.chart-component')).toHaveAttribute('data-point-count', '24')
  await expect(energy.locator('.chart-total')).toContainText('3,280')
  for (const [period, count] of [['Daily', 12], ['Weekly', 12], ['Monthly', 10], ['Yearly', 5], ['Hourly', 24]]) {
    await energy.getByRole('button', { name: period, exact: true }).click()
    await expect(energy.getByRole('button', { name: period, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(energy.locator('.chart-component')).toHaveAttribute('data-period', period.toLowerCase())
    await expect(energy.locator('.chart-component')).toHaveAttribute('data-point-count', String(count))
    await expect(energy.getByRole('img')).toHaveAttribute('aria-label', new RegExp(period.toLowerCase()))
  }
  await expect(water.locator('.chart-component')).toHaveAttribute('data-period', 'hourly')
  await page.getByRole('combobox', { name: 'Filter by location' }).selectOption('block-a')
  await expect(energy.locator('.chart-total')).toContainText('1,240')
  await page.getByRole('link', { name: 'Energy Management', exact: true }).click()
  const comparison = page.locator('.card').filter({ has: page.getByRole('heading', { name: 'Energy by location', exact: true }) })
  await comparison.getByRole('button', { name: 'Yearly', exact: true }).click()
  await expect(comparison.locator('.chart-component')).toHaveAttribute('data-period', 'yearly')
  expect(Number(await comparison.locator('.chart-component').getAttribute('data-total'))).toBeGreaterThan(1240)
})
test('management KPIs remain compact, charts sit below them and equipment tables do not overlap', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.getByRole('link', { name: 'Energy Management', exact: true }).click()
  const kpi = await page.locator('.kpi').first().boundingBox()
  const chart = await page.locator('.chart-card').first().boundingBox()
  expect(kpi.height).toBeLessThan(210)
  expect(kpi.width).toBeLessThan(330)
  expect(chart.y).toBeGreaterThan(kpi.y + kpi.height)
  await page.getByRole('link', { name: 'BMS', exact: true }).click()
  const tables = page.locator('.table-card')
  const first = await tables.nth(0).boundingBox()
  const second = await tables.nth(1).boundingBox()
  expect(second.y).toBeGreaterThanOrEqual(first.y + first.height)
})
