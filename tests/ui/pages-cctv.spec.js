import { test, expect } from '@playwright/test'
test('CCTV demo remains animated when video files fail to load', async ({page}) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/media/*.webm',route=>route.abort())
  await page.goto('/security-cctv')
  const demo=page.locator('.cctv-demo-fallback')
  await expect(demo).toBeVisible()
  await expect(demo).toHaveAttribute('data-playing','true')
  await expect.poll(()=>page.locator('.cctv-caption time').textContent()).not.toContain('02:30:00')
  await page.getByRole('button',{name:'Pause demo footage'}).click()
  await expect(demo).toHaveAttribute('data-playing','false')
  const timestamp=await page.locator('.cctv-caption time').textContent()
  await page.waitForTimeout(250)
  expect(await page.locator('.cctv-caption time').textContent()).toBe(timestamp)
  await page.getByRole('button',{name:'Play demo footage'}).click()
  await expect(demo).toHaveAttribute('data-playing','true')
  await page.getByRole('button',{name:'View Car park camera'}).click()
  await expect(demo).toHaveAttribute('aria-label','Simulated demo footage: Car park')
  await page.getByRole('button',{name:'View East entrance camera'}).click()
  await expect(page.locator('.cctv-unavailable')).toContainText('Camera offline')
  await expect(demo).toHaveCount(0)
  expect(errors).toEqual([])
})

test('each section opens directly, refreshes and supports browser history', async ({ page }) => {
  for (const [path, heading] of [
    ['/dashboard', 'Dashboard'], ['/building-management', 'BMS'],
    ['/energy-management', 'Energy Management'], ['/water-management', 'Water Management'],
    ['/security-cctv', 'Security and CCTV'],
  ]) {
    await page.goto(path)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(heading)
    await page.reload()
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(heading)
    await expect(page.getByRole('link', { name: heading, exact: true })).toHaveAttribute('aria-current', 'page')
  }
  await page.getByRole('link', { name: 'Energy Management', exact: true }).click()
  await expect(page).toHaveURL(/\/energy-management$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/security-cctv$/)
  await page.goForward()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Energy Management')
  await page.goto('/dashboard/digital-twin')
  await expect(page.locator('#twin-panel')).toBeEmpty()
  await page.reload()
  await expect(page.getByRole('tab', { name: /Digital Twin/ })).toHaveAttribute('aria-selected', 'true')
  await page.goto('/missing-page')
  await expect(page.getByRole('heading', { name: 'Page not found' })).toBeVisible()
})

test('local CCTV clips play, pause, switch cameras, show offline state and follow block filter', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/security-cctv')
  const footage = page.locator('.cctv-screen video')
  await expect(footage).toBeVisible()
  await expect.poll(() => footage.evaluate(video => video.readyState)).toBeGreaterThanOrEqual(2)
  await expect.poll(() => footage.evaluate(video => video.currentTime)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Pause demo footage' }).click()
  await expect.poll(() => footage.evaluate(video => video.paused)).toBe(true)
  await page.getByRole('button', { name: 'Play demo footage' }).click()
  await expect.poll(() => footage.evaluate(video => video.paused)).toBe(false)
  await page.getByRole('button', { name: 'Fullscreen CCTV viewer' }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(true)
  await page.evaluate(() => document.exitFullscreen())
  await page.getByRole('button', { name: 'View Car park camera' }).click()
  await expect(footage).toHaveAttribute('src', '/media/cctv-parking.webm')
  await expect.poll(() => footage.evaluate(video => video.readyState)).toBeGreaterThanOrEqual(2)
  await page.getByRole('button', { name: 'View East entrance camera' }).click()
  await expect(page.locator('.cctv-unavailable')).toContainText('Camera offline')
  await expect(page.getByRole('button', { name: 'Play demo footage' })).toBeDisabled()
  await page.getByRole('combobox', { name: 'Filter by location' }).selectOption('block-c')
  await expect(page.locator('.camera-choice')).toHaveCount(1)
  await expect(page.locator('.cctv-caption')).toContainText('Visitor lobby')
  await expect(page.locator('.cctv-disclaimer')).toContainText('not live camera feeds')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/cctv-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/cctv-mobile.png', fullPage: true, animations: 'disabled' })
  expect(errors).toEqual([])
})

