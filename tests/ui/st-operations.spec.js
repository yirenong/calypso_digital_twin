import { test, expect } from '@playwright/test'

test('ST facilities filters cascade and fault reporting uses fixed server-side classification', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'ST-Admin'))
  const calls = []
  await page.route('**/api/st-synthesis?*', async route => {
    const url = new URL(route.request().url()), action = url.searchParams.get('action')
    calls.push({ action, params: Object.fromEntries(url.searchParams), body: route.request().postDataJSON() })
    const data = { sites: [{ id: 32, name: 'Test site' }], buildings: [{ id: 3, name: 'Building A' }], floors: [{ id: 4, name: 'Floor 1' }], rooms: [{ id: 6, name: 'Room 6' }], faults: [{ id: 1, fault_number: 'NPK1234', status: 'Work_started' }], maintenance: [{ id: 2, title: 'Scheduled cleaning' }] }
    await route.fulfill({ json: action === 'report' ? { success: true } : { data: data[action] || [], meta: { pagination: { total: 11 } } } })
  })
  await page.goto('/st/operations')
  await expect(page.getByRole('heading', { name: 'Facilities operations' })).toBeVisible()
  await expect(page.getByText('Connected', { exact: true })).toBeVisible()
  expect(calls[0].action).toBe('login')
  expect(calls[1].action).toBe('sites')
  await expect(page.getByRole('button', { name: /Test site.*View site records/ })).toBeVisible()
  await expect(page.locator('.overview')).toHaveCount(0)
  await page.getByRole('button', { name: /Test site.*View site records/ }).click()
  await expect(page.getByRole('button', { name: /Test site.*View site records/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('combobox', { name: 'building', exact: true }).selectOption('3')
  await page.getByRole('combobox', { name: 'floor', exact: true }).selectOption('4')
  await page.getByRole('combobox', { name: 'room', exact: true }).selectOption('6')
  await expect(page.getByRole('heading', { name: 'NPK1234', exact: true })).toBeVisible()
  await expect(page.getByText('11 faults', { exact: true })).toBeVisible()
  await expect(page.getByLabel('From', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Date range', exact: true }).click()
  await expect(page.getByLabel('From', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Date range', exact: true }).click()
  await expect(page.getByText('Page 1 of 2', { exact: false })).toBeVisible()
  expect(calls.some(c => c.action === 'faults' && c.params.room === '6')).toBeTruthy()
  await page.getByRole('button', { name: 'Preventive maintenance', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Scheduled cleaning' })).toBeVisible()
  expect(calls.some(c => c.action === 'maintenance' && c.params.pm_room_id === '6')).toBeTruthy()
  await page.getByRole('button', { name: 'Report a fault', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Report a fault', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Report site', exact: true })).toHaveValue('32')
  await expect(page.getByLabel('What needs attention?', { exact: false })).toBeFocused()
  await page.getByRole('combobox', { name: 'Report site', exact: true }).selectOption('32')
  await page.getByRole('button', { name: 'Submit fault', exact: true }).click()
  await expect(page.getByText('Fault reported successfully.')).toBeVisible()
  expect(calls.find(c => c.action === 'report').body).toEqual({ site_id: 32, fault_remarks: '' })
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.screenshot({ path: 'tmp/st-operations-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 0)
  await expect(page.getByRole('heading', { name: 'Facilities operations' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'tmp/st-operations-mobile.png', fullPage: true })
})

test('report modal supports dismissal, preserves failed requests and retries without losing input', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'ST-Admin'))
  let attempts = 0
  await page.route('**/api/st-synthesis?*', async route => {
    const action = new URL(route.request().url()).searchParams.get('action')
    if (action === 'report') {
      attempts++
      return route.fulfill({ status: attempts === 1 ? 502 : 200, json: attempts === 1 ? { error: 'Service temporarily unavailable.' } : { success: true } })
    }
    await route.fulfill({ json: { data: action === 'sites' ? [{ id: 32, name: 'Test site' }] : [] } })
  })
  await page.goto('/st/operations')
  const trigger = page.getByRole('button', { name: 'Report a fault', exact: true })
  await expect(page.getByText('Connected', { exact: true })).toBeVisible()
  await trigger.click()
  const modal = page.getByRole('dialog', { name: 'Report a fault', exact: true })
  await expect(modal).toBeVisible()
  await expect(modal.getByRole('combobox')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(modal).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await modal.getByRole('combobox').selectOption('32')
  await modal.getByRole('textbox').fill('Please clean near the entrance.')
  await page.screenshot({ path: 'tmp/st-report-modal-desktop.png' })
  await modal.getByRole('button', { name: 'Submit fault', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('send your fault report')
  await expect(modal.getByRole('alert')).not.toContainText('Service temporarily unavailable.')
  await expect(modal.getByRole('textbox')).toHaveValue('Please clean near the entrance.')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'tmp/st-report-modal-mobile.png' })
  expect(await modal.evaluate(el => el.getBoundingClientRect().width <= window.innerWidth)).toBeTruthy()
  await modal.getByRole('button', { name: 'Submit fault', exact: true }).click()
  await expect(modal).not.toBeVisible()
  expect(attempts).toBe(2)
  await expect(page.getByText('Fault reported successfully.')).toBeVisible()
})

test('every endpoint has an independent request button and shows upstream errors', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'ST-Admin'))
  const calls = []
  await page.route('**/api/st-synthesis?*', async route => {
    const url = new URL(route.request().url())
    calls.push({ action: url.searchParams.get('action'), params: Object.fromEntries(url.searchParams), method: route.request().method() })
    await route.fulfill({ json: url.searchParams.has('inspect') ? { ok: false, status: 404, response: { message: 'Endpoint not found' } } : { data: [] } })
  })
  await page.goto('/st/operations')
  const console = page.locator('.api-console')
  await console.locator('summary').first().click()
  for (const [method, path] of [['POST','auth/login'],['GET','my_sites'],['GET','buildings'],['GET','floors'],['GET','room'],['GET','faults'],['GET','preventive_maintenances'],['POST','report_a_fault'],['GET','sync_sites']]) {
    await expect(console.getByRole('button', { name: `${method} /api/${path}`, exact: true })).toBeVisible()
  }
  await console.getByRole('button', { name: 'POST /api/auth/login', exact: true }).click()
  await expect(console.getByRole('region', { name: 'auth/login', exact: true }).getByRole('alert')).toContainText('HTTP 404')
  const buildings = console.getByRole('region', { name: 'buildings', exact: true })
  await buildings.getByRole('textbox').fill('32')
  await buildings.getByRole('button').click()
  await expect(buildings.getByRole('alert')).toContainText('Endpoint not found')
  expect(calls.some(c => c.action === 'login' && c.method === 'POST')).toBeTruthy()
  expect(calls.some(c => c.action === 'buildings' && c.params.site_id === '32')).toBeTruthy()
  await expect(console.getByText('https://st-synthesis.ctrl-tower.mymachinecity.com', { exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'API environment', exact: true })).toHaveCount(0)
})

