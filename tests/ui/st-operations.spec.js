test('fault details open in an accessible modal and status availability filters keep pagination usable', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('calypso-demo-session', 'ST-Admin'))
  await page.route('**/api/st-synthesis?*', async route => {
    const action = new URL(route.request().url()).searchParams.get('action')
    await route.fulfill({ json: { data: action === 'faults' ? [{ id: 1, fault_number: 'FAULT-1', latest_status: 'Work_started', fault_remarks: 'Lighting issue', site_and_location: { data: { floor_id: 4 } } }, { id: 2, fault_number: 'FAULT-2', latest_status: null }] : [], meta: { pagination: { total: 21 } } } })
  })
  await page.goto('/st/operations')
  const availability = page.getByRole('combobox', { name: 'Status availability', exact: true })
  await expect(page.getByRole('heading', { name: 'FAULT-1', exact: true })).toBeVisible()
  const trigger = page.getByRole('button', { name: 'View details for FAULT-1', exact: true })
  await trigger.click()
  const modal = page.getByRole('dialog', { name: 'FAULT-1', exact: true })
  await expect(modal).toBeVisible()
  await expect(modal.getByText('Lighting issue', { exact: true }).first()).toBeVisible()
  await expect(modal.getByText('site and location', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'tmp/st-fault-details-desktop.png' })
  await page.keyboard.press('Escape')
  await expect(modal).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await availability.selectOption('available')
  await expect(page.getByRole('heading', { name: 'FAULT-1', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'FAULT-2', exact: true })).toHaveCount(0)
  await availability.selectOption('unavailable')
  await expect(page.getByRole('heading', { name: 'FAULT-2', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'FAULT-1', exact: true })).toHaveCount(0)
  await expect(page.getByText('Showing 1 of 2 records on this page.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(availability).toHaveValue('all')
  await expect(trigger).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await trigger.click()
  await expect(modal).toBeVisible()
  await page.screenshot({ path: 'tmp/st-fault-details-mobile.png' })
  expect(await modal.evaluate(el => el.getBoundingClientRect().width <= window.innerWidth)).toBeTruthy()
  await modal.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(modal).not.toBeVisible()
})
