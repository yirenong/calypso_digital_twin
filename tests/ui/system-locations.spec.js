import { test, expect } from '@playwright/test'
test('system inventories and sensors follow the configured levels', async ({page}) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/energy-management/sensors')
  await expect(page.getByLabel('Sensor location')).toHaveText(/Level 5/)
  await page.getByLabel('Sensor location').selectOption('level-4')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(1)
  await expect(page.locator('.sensor-inventory tbody tr')).toContainText('Cooling Tower System')
  await page.getByLabel('Sensor location').selectOption('level-5')
  await expect(page.getByText('No sensors match these filters.')).toBeVisible()
  await page.goto('/building-management')
  await page.getByLabel('Filter by location').selectOption('block-a')
  await expect(page.locator('.table-card').last()).toContainText('Chiller Plant System')
  await expect(page.locator('.table-card').last()).toContainText('HVAC Pump System')
  await page.getByLabel('Filter by location').selectOption('level-4')
  await expect(page.locator('.table-card').last()).toContainText('Cooling Tower System')
  await expect(page.locator('.table-card').last()).not.toContainText('Water Supply System')
  await page.goto('/water-management/sensors')
  await page.getByLabel('Sensor location').selectOption('block-c')
  await page.getByLabel('Sensor system').selectOption('waste-water')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(2)
  await page.goto('/water-management')
  await page.getByLabel('Filter by location').selectOption('landscape')
  await expect(page.getByRole('status')).toContainText('No systems or readings')
  expect(errors).toEqual([])
})
