import { test, expect } from '@playwright/test'
test('individual sensor pages filter health, inspect histories and react to telemetry', async ({page}) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/energy-management')
  await page.getByRole('link',{name:'Sensors',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Energy Management sensors'})).toBeVisible()
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(9)
  await page.getByLabel('Sensor status',{exact:true}).selectOption('Faulty')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(1)
  await expect(page.locator('.sensor-diagnostics')).toContainText('SENSOR_SIGNAL_INVALID')
  await expect(page.locator('.sensor-inventory tbody tr')).toContainText('Unavailable')
  await page.getByLabel('Sensor status',{exact:true}).selectOption('all')
  await page.getByRole('button',{name:'Inspect energy-a-01',exact:true}).click()
  await page.evaluate(async()=>{const api=await import('/calypso-data.js');api.updateSensor('energy-a-01',{rate:100})})
  await expect(page.locator('.sensor-diagnostics .sensor-status')).toHaveText('Abnormal')
  const chart=page.locator('.sensor-chart')
  for(const label of ['Hourly','Daily','Weekly','Monthly','Yearly']) { await chart.getByRole('button',{name:label,exact:true}).click();await expect(chart.locator('.chart-component')).toHaveAttribute('data-period',label.toLowerCase()) }
  await chart.getByRole('button',{name:'Daily',exact:true}).click()
  await page.getByLabel('Sensor consumption From',{exact:true}).fill('2026-10-02')
  await page.getByLabel('Sensor consumption To',{exact:true}).fill('2026-10-04')
  await chart.getByRole('button',{name:'Apply',exact:true}).click()
  await expect(chart.locator('.chart-component')).toHaveAttribute('data-point-count','3')
  await page.goto('/water-management/sensors')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(12)
  await page.getByLabel('Sensor status',{exact:true}).selectOption('Offline')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(1)
  await expect(page.locator('.sensor-diagnostics')).toContainText('Communication lost')
  await page.getByLabel('Sensor status',{exact:true}).selectOption('Abnormal')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(1)
  await expect(page.locator('.sensor-diagnostics')).toContainText('does not prove')
  await page.getByLabel('Sensor status',{exact:true}).selectOption('all')
  await page.getByLabel('Sensor location',{exact:true}).selectOption('block-c')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(4)
  await page.getByLabel('Search sensors',{exact:true}).fill('Waste water System meter 1')
  await expect(page.locator('.sensor-inventory tbody tr')).toHaveCount(1)
  await page.getByLabel('Search sensors',{exact:true}).fill('nonexistent')
  await expect(page.getByText('No sensors match these filters.')).toBeVisible()
  await page.getByLabel('Search sensors',{exact:true}).fill('')
  await page.reload();await expect(page.getByRole('heading',{name:'Water Management sensors'})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
