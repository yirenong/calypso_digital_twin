import { test, expect } from '@playwright/test'
test('active reminders preserve elapsed time across refresh and obey interval changes', async ({page}) => {
  await page.clock.install()
  await page.goto('/water-management/thresholds')
  await page.getByLabel('Enable Supply pressure threshold').check()
  await page.getByLabel('Supply pressure block').selectOption('block-b')
  await page.getByLabel('Supply pressure limit').fill('3')
  await expect(page.getByLabel('Notification interval in minutes')).toHaveValue('3')
  await page.getByRole('button',{name:'Save thresholds'}).click()
  const count=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('calypso.notifications.v1')||'[]').length)
  await expect.poll(count).toBe(1)
  await page.clock.fastForward(120000)
  await page.reload()
  await expect(page.getByRole('heading',{name:'Water Management thresholds'})).toBeVisible()
  expect(await count()).toBe(1)
  await expect(page.locator('.notification-toast')).toHaveCount(0)
  await page.clock.fastForward(59000)
  expect(await count()).toBe(1)
  await page.clock.fastForward(1000)
  await expect.poll(count).toBe(2)
  await page.getByLabel('Notification interval in minutes').fill('5')
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await page.clock.fastForward(180000)
  expect(await count()).toBe(2)
  await page.reload()
  await expect(page.getByLabel('Notification interval in minutes')).toHaveValue('5')
  expect(await count()).toBe(2)
  await page.clock.fastForward(120000)
  await expect.poll(count).toBe(3)
  await page.getByRole('button',{name:'Notifications',exact:true}).click()
  await page.getByRole('button',{name:'Clear history'}).click()
  await page.getByRole('button',{name:'Close notifications'}).click()
  await page.reload()
  await expect(page.getByRole('heading',{name:'Water Management thresholds'})).toBeVisible()
  expect(await count()).toBe(0)
  await page.getByLabel('Enable Supply pressure threshold').uncheck()
  await page.getByRole('button',{name:'Save thresholds'}).click()
  await page.clock.fastForward(600000)
  expect(await count()).toBe(0)
})
