import {test,expect} from '@playwright/test'

test('cards adapt to viewer size and fullscreen without overwriting saved sizes',async({page})=>{
 await page.setViewportSize({width:1100,height:900})
 await page.addInitScript(()=>sessionStorage.setItem('calypso-demo-session','admin'))
 await page.route('**/visualiser/**',r=>r.fulfill({body:'Unity'}))
 await page.goto('/dashboard/digital-twin')
 const health=page.locator('[data-panel="health"]')
 await expect(health).toHaveClass(/collapsed/)
 await page.getByRole('button',{name:'Expand Sensor health panel',exact:true}).click()
 await expect(health).not.toHaveClass(/collapsed/)
 const overview=page.locator('[data-panel="overview"]')
 const small=await overview.boundingBox()
 await page.setViewportSize({width:1920,height:1080})
 await expect.poll(async()=> (await overview.boundingBox()).width).toBeGreaterThan(small.width)
 await page.getByRole('button',{name:'Fullscreen digital twin'}).click()
 const bounds=await page.locator('.twin-overlays').boundingBox()
 const box=await overview.boundingBox()
 expect(box.width).toBeLessThanOrEqual(320)
 expect(box.x).toBeGreaterThanOrEqual(bounds.x)
 await page.evaluate(()=>document.exitFullscreen())
 await page.setViewportSize({width:1100,height:900})
 await expect.poll(async()=> (await overview.boundingBox()).width).toBeCloseTo(small.width,0)
 expect(await page.evaluate(()=>localStorage.getItem('calypso.twin.free-layout.v1'))).toBeNull()
})
