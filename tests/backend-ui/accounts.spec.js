import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import pg from 'pg'

const passwords = Object.fromEntries(readFileSync('.env.account-credentials', 'utf8').trim().split(/\r?\n/).map(line => line.split(': ')))
test('fresh browsers restore settings, accounts stay separate, failed saves retry', async ({ browser }) => {
  expect(process.env.CALYPSO_TEST_DATABASE).toBe('true')
  const db = new pg.Client({ connectionString: process.env.DATABASE_URL })
  await db.connect()
  await db.query('DELETE FROM calypso_settings')
  await db.query('DELETE FROM calypso_login_limits')
  const contexts = []
  async function open(username) {
    const context = await browser.newContext()
    contexts.push(context)
    await context.route('**/visualiser/**', route => route.fulfill({ contentType: 'text/html', body: 'Viewer test' }))
    const page = await context.newPage()
    await page.goto('/login')
    await page.getByLabel('Username', { exact: true }).fill(username)
    await page.getByLabel('Password', { exact: true }).fill(passwords[username])
    await page.getByRole('button', { name: 'Sign in to workspace' }).click()
    await expect(page.locator('.account-name')).toHaveText(username)
    return page
  }
  try {
    const st = await open('ST-Admin')
    await st.getByRole('link', { name: 'Energy Management', exact: true }).click()
    await st.getByRole('button', { name: 'Favorite Energy by location', exact: true }).click()
    await expect(st.locator('.sync-status')).toHaveText('Saved to account')
    await st.getByRole('link', { name: 'Dashboard', exact: true }).click()
    await st.getByRole('button', { name: 'Customize dashboard' }).click()
    await st.getByRole('button', { name: 'Remove Indoor temperature' }).click()
    await st.getByRole('button', { name: 'Save dashboard' }).click()
    await expect(st.locator('.sync-status')).toHaveText('Saved to account')
    const fresh = await open('ST-Admin')
    await expect(fresh.locator('.widget-grid')).not.toContainText('Indoor temperature')
    await fresh.getByRole('link', { name: 'Energy Management', exact: true }).click()
    await expect(fresh.getByRole('button', { name: 'Unfavorite Energy by location', exact: true })).toBeVisible()
    const pp = await open('PowerPlus-Admin')
    await expect(pp.locator('.widget-grid')).toContainText('Indoor temperature')
    await pp.getByRole('link', { name: 'Energy Management', exact: true }).click()
    await expect(pp.getByRole('button', { name: 'Favorite Energy by location', exact: true })).toBeVisible()
    await pp.route('**/api/settings', route => route.request().method() === 'PATCH' ? route.abort() : route.continue())
    await pp.getByRole('button', { name: 'Favorite Energy by location', exact: true }).click()
    await expect(pp.locator('.sync-status')).toHaveClass(/error/)
    await pp.unroute('**/api/settings')
    await pp.locator('.sync-status').click()
    await expect(pp.locator('.sync-status')).toHaveText('Saved to account')
    const restoredPP = await open('PowerPlus-Admin')
    await restoredPP.getByRole('link', { name: 'Energy Management', exact: true }).click()
    await expect(restoredPP.getByRole('button', { name: 'Unfavorite Energy by location', exact: true })).toBeVisible()
    await fresh.goto('/water-management/thresholds')
    await fresh.getByLabel('Notification interval in minutes').fill('5')
    await fresh.getByRole('button', { name: 'Save thresholds' }).click()
    await expect(fresh.locator('.sync-status')).toHaveText('Saved to account')
    await st.goto('/water-management/thresholds')
    await expect(st.getByLabel('Notification interval in minutes')).toHaveValue('5')
    await restoredPP.goto('/water-management/thresholds')
    await expect(restoredPP.getByLabel('Notification interval in minutes')).toHaveValue('3')
    await restoredPP.goto('/powerplus/operational')
    await expect(restoredPP.getByTestId('tse-value')).toContainText('0.72')
    await expect(restoredPP.locator('.acmv-efficiency')).toContainText('Backend sample')
    await restoredPP.getByLabel('Task', { exact: true }).fill('Backend workflow')
    await restoredPP.getByLabel('Equipment', { exact: true }).selectOption({ index: 1 })
    await restoredPP.getByLabel('Assigned to', { exact: true }).fill('PowerPlus FM')
    await restoredPP.getByRole('button', { name: 'Create work order', exact: true }).click()
    await expect(restoredPP.locator('.sync-status')).toHaveText('Saved to account')
    const freshPowerPlus = await open('PowerPlus-Admin')
    await freshPowerPlus.goto('/powerplus/operational')
    await expect(freshPowerPlus.getByLabel('Status for Backend workflow', { exact: true })).toHaveValue('Pending')
    await freshPowerPlus.getByRole('link', { name: 'Adaptive AC', exact: true }).click()
    await freshPowerPlus.getByLabel('Control mode', { exact: true }).selectOption('Manual')
    await freshPowerPlus.getByLabel('Manual fan speed (%)', { exact: true }).fill('80')
    await freshPowerPlus.getByRole('button', { name: 'Apply AC controls', exact: true }).click()
    await expect(freshPowerPlus.locator('.sync-status')).toHaveText('Saved to account')
    await restoredPP.goto('/adaptive-ac')
    await expect(restoredPP.getByLabel('Control mode', { exact: true })).toHaveValue('Manual')
    await expect(restoredPP.getByLabel('Manual fan speed (%)', { exact: true })).toHaveValue('80')
    await st.goto('/powerplus/operational')
    await expect(st).toHaveURL(/\/dashboard$/)
    await fresh.getByRole('button', { name: 'Sign out', exact: true }).first().click()
    await fresh.getByRole('dialog').getByRole('button', { name: 'Sign out', exact: true }).click()
    await expect(fresh).toHaveURL(/\/login$/)
    expect((await fresh.request.get('/api/settings')).status()).toBe(401)
  } finally {
    await Promise.all(contexts.map(context => context.close()))
    await db.query('DELETE FROM calypso_settings')
    await db.query('DELETE FROM calypso_sessions')
    await db.query('DELETE FROM calypso_login_limits')
    await db.end()
  }
})
